/* Build the single-file Client module expected by window.__ModuleLoader__. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const engine = readFileSync(join(here, 'src', 'engine.js'), 'utf8');
const ui = readFileSync(join(here, 'src', 'ui.js'), 'utf8');

const out = `/* Generated by build.mjs — do not edit client.js directly. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react');
    const h = React.createElement;

/* ======================= engine ======================= */
${engine}
/* ========================= ui ========================= */
${ui}
/* ======================= bootstrap ==================== */
    const engine = createControlEngine();

    return {
      inject: ['slots', 'locale'],
      apply(ctx) {
        const locale = ctx.get('locale');
        let translator = null;
        if (locale) {
          try {
            ctx.effect(() => locale.register('control-lab', 'zh', CONTROL_LAB_ZH));
            ctx.effect(() => locale.register('control-lab', 'zh-CN', CONTROL_LAB_ZH));
            ctx.effect(() => locale.register('control-lab', 'en', CONTROL_LAB_EN));
            ctx.effect(() => locale.register('control-lab', 'en-US', CONTROL_LAB_EN));
          } catch (err) {
            console.error('[${pkg.name}] locale registration failed', err);
          }
          try {
            translator = locale.bind('control-lab');
          } catch (err) {
            console.error('[${pkg.name}] locale binding failed', err);
          }
        }

        const t = (key) => {
          if (!translator) return key;
          try {
            return translator(key) || key;
          } catch (err) {
            return key;
          }
        };

        const ui = createControlLabUI(React, h, engine, t);

        ctx.effect(() => ctx.slots.inject('conversation.input.left', () => ctx.slots.register({
          name: 'conversation.input.left',
          id: 'control-lab.launch',
          order: 24,
          label: () => t('launch'),
        }, ui.Launcher)));

        ctx.effect(() => ctx.slots.inject('shell.overlay', () => ctx.slots.register({
          name: 'shell.overlay',
          id: 'control-lab.overlay',
          order: 120,
        }, ui.Overlay)));
      },
    };
  },
});
`;

writeFileSync(join(here, 'client.js'), out, 'utf8');
console.log('client.js written:', out.length, 'bytes');
